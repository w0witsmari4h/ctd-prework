# This script is intended to determine what kind of coat my toddler needs to put on before playing outside today.

# temperature must be in fahrenheit
temperature = float(input("What's the temperature (in Fahrenheit) outside? "))
# weather options are raining, sunny, cloudy, or snowing
weather = input ("What's the weather like? (raining, sunny, cloudy, or snowing) ").lower()

# rain, snow, and anything 60 degrees or under means a coat.  Everything else, it depends on the temp outside
if weather == "raining" or weather == "snowing" or temperature <= 60:
  print (f"It's {weather} outside and {temperature}°F, so she definitely needs a heavy coat.")
elif temperature < 70:
  print (f"It's {weather} outside and {temperature}°F, so she doesn't need a heavy coat, but at least a light jacket.")
else:
  print (f"It's {weather} outside and {temperature}°F, so no jacket needed!  Have fun!")

